{-# OPTIONS_GHC -Wall #-}

-- | Find the source file of each module of a component, the way Cabal does.
--
-- > find_modules SRCDIR OUT [--dir=DIR]... [--module=MODULE]... [--main=FILE]
--
-- As in preprocessModule (Distribution.Simple.PreProcess), a module is looked
-- for in every DIR, first as the input of a preprocessor Cabal knows, then as
-- a Haskell source file. main-is is looked for as the input of a
-- preprocessor by its name without extensions, and otherwise as it is, which
-- is what GHC is given. The
-- suffixes are Cabal's own (knownSuffixHandlers, builtinHaskellSuffixes), so
-- a preprocessor Cabal adds is found too, and the rules then say they cannot
-- run it rather than look past the file. The result, in OUT:
--
-- > { "modules": { "Data.Foo": { "dir": "src", "file": "Data/Foo.x", "ext": "x", "preprocess": true } }
-- > , "main": { "dir": "app", "file": "Main.hs", "ext": "hs", "preprocess": false }
-- > }
--
-- Modules that are not found are left out; deciding whether that is an
-- error is up to the caller, since they could be autogenerated.
module Main (main) where

import Data.ByteString.Lazy qualified as LBS
import Data.List (stripPrefix)
import Distribution.Simple.PreProcess (builtinHaskellSuffixes, knownSuffixHandlers)
import Distribution.Simple.PreProcess.Types (Suffix (..))
import Distribution.Utils.Json (Json (..), renderJson, (.=))
import System.Directory (doesFileExist)
import System.Environment (getArgs)
import System.Exit (die)
import System.FilePath (splitExtensions, (<.>), (</>))

data Options = Options
    { optDirs :: [FilePath]
    , optModules :: [String]
    , optMain :: Maybe FilePath
    }

parseArgs :: [String] -> Either String (FilePath, FilePath, Options)
parseArgs (srcdir : out : rest) = (,,) srcdir out <$> foldr opt (Right (Options [] [] Nothing)) rest
  where
    opt arg acc = do
        o <- acc
        case arg of
            _ | Just d <- stripPrefix "--dir=" arg -> Right o{optDirs = d : optDirs o}
              | Just m <- stripPrefix "--module=" arg -> Right o{optModules = m : optModules o}
              | Just f <- stripPrefix "--main=" arg -> Right o{optMain = Just f}
              | otherwise -> Left ("unexpected argument: " ++ arg)
parseArgs _ = Left "usage: find_modules SRCDIR OUT [--dir=DIR]... [--module=MODULE]... [--main=FILE]"

main :: IO ()
main = do
    (srcdir, out, opts) <- either (die . ("find_modules: " ++)) pure . parseArgs =<< getArgs
    let find base suffixes = do
            pp <- lookupFile srcdir (optDirs opts) preprocessorSuffixes base
            case pp of
                Just (dir, ext) -> pure (Just (entry dir base ext True))
                Nothing -> fmap (\(dir, ext) -> entry dir base ext False) <$> lookupFile srcdir (optDirs opts) suffixes base
    modules <- mapM (\m -> fmap ((,) m) <$> find (map dot m) haskellSuffixes) (optModules opts)
    mainIs <- case splitExtensions <$> optMain opts of
        Nothing -> pure Nothing
        Just (base, ext) -> find base [drop 1 ext]
    LBS.writeFile out . renderJson . JsonObject $
        ("modules" .= JsonObject [(m, e) | Just (m, e) <- modules])
            : maybe [] (\e -> ["main" .= e]) mainIs
  where
    dot '.' = '/'
    dot c = c

    entry dir base ext preprocess =
        JsonObject
            [ "dir" .= JsonString dir
            , "file" .= JsonString (base <.> ext)
            , "ext" .= JsonString ext
            , "preprocess" .= JsonBool preprocess
            ]

preprocessorSuffixes :: [String]
preprocessorSuffixes = [s | (Suffix s, _) <- knownSuffixHandlers]

haskellSuffixes :: [String]
haskellSuffixes = [s | Suffix s <- builtinHaskellSuffixes]

-- | The first directory, then the first suffix, with a file of that name
-- (findFileCwdWithExtension').
lookupFile :: FilePath -> [FilePath] -> [String] -> FilePath -> IO (Maybe (FilePath, String))
lookupFile srcdir dirs suffixes base = firstM [(dir, ext) | dir <- dirs, ext <- suffixes]
  where
    firstM [] = pure Nothing
    firstM ((dir, ext) : rest) = do
        found <- doesFileExist (srcdir </> dir </> base <.> ext)
        if found then pure (Just (dir, ext)) else firstM rest
